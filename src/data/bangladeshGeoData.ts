// Helper function to get districts for a given division
export const getDistrictsByDivision = (division: string): string[] => {
  return DISTRICTS_BY_DIVISION[division] || [];
};

// Helper function to get upazilas for a given district
export const getUpazilasByDistrict = (district: string): string[] => {
  return UPAZILAS_BY_DISTRICT[district] || [];
};

// Helper function to find which division a district belongs to
export const getDivisionByDistrict = (district: string): string => {
  for (const [div, distList] of Object.entries(DISTRICTS_BY_DIVISION)) {
    if (distList.includes(district)) {
      return div;
    }
  }
  return '';
};

